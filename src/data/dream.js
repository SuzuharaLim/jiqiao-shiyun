// 依關鍵字比對。⚠️ 要用「最長關鍵字優先」，否則「撿到錢」會先被短的「錢」吸走，
// 而那兩條的斷語剛好相反（反夢），配錯就是給出完全顛倒的答案。
// ⚠️ k[0] 同時是網址 slug 與頁面標題，必須放「使用者實際會搜的詞」——
//    「夢見掉牙」的搜尋量遠大於「夢見牙」。比對本身會掃過 k 的所有詞，不受順序影響。
// ⚠️ 一定要回傳「比對到哪個關鍵字」。輸入「我夢到我變成一台冰箱而且會飛」時
//    其實只比對到「飛」，畫面卻原封不動印出整句加上「《周公解夢》原典：身在空中飛，
//    主大吉」——看起來像古書真的針對「變成冰箱」講了這句話。
//    同時回傳其他有比對到的詞，讓使用者可以改選（一句話裡常有好幾個夢象）。
export function lookupDream(input) {
  const q = (input || '').trim()
  if (!q) return null
  const hits = []
  for (const d of DREAMS) {
    let kw = '', len = 0
    for (const k of d.k) if (q.includes(k) && k.length > len) { kw = k; len = k.length }
    if (kw) hits.push({ d, kw, len })
  }
  if (!hits.length) return null
  hits.sort((a, b) => b.len - a.len)
  const best = hits[0]
  // 附上「命中的關鍵字」與其他候選（去掉同一條）
  return { ...best.d, matchedKeyword: best.kw, alsoMatched: hits.slice(1).map(h => ({ kw: h.kw, term: h.d.k[0] })) }
}

// 夢的五行 vs 當日日干支五行 → 延伸提示。
// ⚠️ 整修前不論做什麼夢都吐同一句「宜緩不宜急……放到吉時再拍板」，
//    重複感很重，而且與夢境內容毫無關係。改為依生剋分流。
const SHENG = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' }   // 我生
const KE = { 木: '土', 火: '金', 土: '水', 金: '木', 水: '火' }      // 我剋
export function dreamExtend(wx, dayWx) {
  if (!wx || !dayWx) return null
  if (wx === dayWx) return `夢象屬${wx}，與今日日柱同氣——心裡想的與當下的節奏是同一個方向，可順勢而為。`
  if (SHENG[wx] === dayWx) return `夢象屬${wx}，生今日之${dayWx}——力氣是往外給的，記得留一些給自己。`
  if (SHENG[dayWx] === wx) return `今日之${dayWx}生夢象之${wx}——外在條件正在幫你，適合把想做的事推進一步。`
  if (KE[wx] === dayWx) return `夢象屬${wx}，剋今日之${dayWx}——想法比現實跑得快，先確認手上的資源再動。`
  return `今日之${dayWx}剋夢象之${wx}——外在阻力偏大，這幾天宜守不宜攻。`
}
