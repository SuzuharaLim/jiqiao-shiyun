// 袁天罡秤骨神術 —— 骨重對照表與計算。
//
// 傳統作法：把「農曆」出生年（六十甲子）、月、日、時辰四項各自的骨重相加，
// 得總骨重（單位 兩／錢，1 兩 = 10 錢），再對照命格。
//
// 資料來源：算準網《袁天罡稱骨算命對照表》
//   https://www.suanzhun.net/chengu/1773.html
// ⚠️ 坊間版本的骨重表略有差異（尤其日骨重），故 UI 需標明依據版本；
//    先前這支功能是用 (年+月+日) % 5 自創公式，與任何一版都對不上，已廢除。
// ⚠️ 一律以農曆計算。使用者若輸入國曆，必須先經 lunisolar 轉換再查表。

// 六十甲子年骨重（單位：錢）。索引＝六十甲子序（甲子=0 … 癸亥=59）。
