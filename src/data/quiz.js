export function loadBoards() {
  try {
    const raw = localStorage.getItem(KEY)
    if (raw) {
      const o = JSON.parse(raw)
      if (o && Array.isArray(o.solo) && Array.isArray(o.duel)) return o
    }
  } catch { /* 存取被擋：用記憶體版 */ }
  return mem
}

export function pushScore(name, score, mode) {
  const all = loadBoards()
  const entry = { name: name || '訪客', score, at: Date.now() }
  const list = (all[mode] || []).concat(entry).sort((a, b) => b.score - a.score).slice(0, 10)
  const next = { ...all, [mode]: list }
  mem = next
  try { localStorage.setItem(KEY, JSON.stringify(next)) } catch { /* 同上 */ }
  return entry
}

// ════════════════ 真人對戰：兩邊必須拿到同一副牌 ════════════════
//
// ★★★ 對戰的公平性建立在「同一副牌、同樣的選項順序」上。
//   shuffle() 用 Math.random，兩台裝置各洗各的 ⇒ 題目與選項都不一樣，
//   那就不是同一場比賽了。所以對戰一律用**種子**產生，種子由伺服器發。
// ⚠️ 這是純函式：同一個 seed 在任何裝置、任何時間都得到同一個結果，
//    伺服器驗證答案時也用它，不必把整副牌存進資料庫。

/** 32-bit 字串雜湊 → 種子。 */
function hashSeed(str) {
  const t = String(str)
  let h = 2166136261
  for (let i = 0; i < t.length; i++) { h ^= t.charCodeAt(i); h = Math.imul(h, 16777619) }
  return h >>> 0
}

/** mulberry32：小、快、夠均勻的可重現亂數。 */
function rng(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6D2B79F5) >>> 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** 用種子洗一個陣列（Fisher–Yates，不改動原陣列）。 */
function seededShuffle(arr, rand) {
  const a = arr.slice()
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1))
    const tmp = a[i]; a[i] = a[j]; a[j] = tmp
  }
  return a
}

/**
 * 對戰用的牌：題目順序與**每題的選項順序**都由種子決定。
 * @param {string} seed 伺服器發的種子
 * @param {number} n    要幾題（不足就繞回去接，長局才不會發完）
 */
export function seededDeck(seed, n = 60) {
  const rand = rng(hashSeed(seed))
  const order = seededShuffle(QUESTIONS, rand)
  const out = []
  for (let i = 0; i < n; i++) {
    const src = order[i % order.length]
    const correct = src.o[0]
    const opts = seededShuffle(src.o, rand)
    out.push({ q: src.q, tag: src.tag, why: src.why, opts, ans: opts.indexOf(correct) })
  }
  return out
}

// ── 分數上界：伺服器用來夾住送上來的分數 ──────────────────────
//
// ★★★ 放在這裡而不是 server/badges.js，是為了讓建置閘門
//   （scripts/check-badges.mjs）能直接 import 它**而不會牽到 server/db.js**。
//   閘門一旦 import 到資料層，就有能力在容器建置情境下擋掉正式部署
//   ——站規記過一次真實事故（check-map.mjs 讀 docs/ 把部署整個卡住）。
//   純函式放純資料層，那個風險就從根本上不存在。
//
// ⚠️ 誠實話：題庫在前端 bundle 裡，看得到答案的人仍然可以每題都答對，
//    所以這**不是**防作弊，只是讓分數必須與「答對幾題」自洽（擋掉直接送 999999）。
//
// 計分公式（QuizGame.jsx）：gain = round((100 + speed*120) * (1 + floor(combo/3)))
//   speed ≤ 1（瞬間作答），combo 是「這一題是第幾個連對」。
//   n 題全對的理論上界 = Σ_{c=1..n} 220 * (1 + floor(c/3))。
export function maxScoreFor(right) {
  const n = Math.max(0, Math.min(200, Math.floor(right) || 0))
  let sum = 0
  for (let c = 1; c <= n; c++) sum += 220 * (1 + Math.floor(c / 3))
  return sum
}
