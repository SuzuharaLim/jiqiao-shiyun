/** Fisher–Yates。`sort(() => Math.random()-.5)` 的分布是歪的，別用。 */
export function shuffle(arr) {
  const a = arr.slice()
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

/** 發一題：洗好選項並回報正解洗到第幾個 */
export function dealt(src) {
  const correct = src.o[0]
  const opts = shuffle(src.o)
  return { q: src.q, tag: src.tag, why: src.why, opts, ans: opts.indexOf(correct) }
}

