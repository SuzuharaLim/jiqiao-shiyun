// ── 比對與輸出 ──────────────────────────────────────────────────
// ⚠️ 只在「明確命中」時才接手。開放式的問題（今天適合做什麼、節氣養生、
//    解籤、閒聊）一律讓給 GPT——本地層不是要取代 AI，是要把
//    「模型不該回答的題目」先攔下來。硬做成 FAQ 機器人反而更糟。
//
// ⚠️ 三條比對規則，順序不可調換：
//    1. 安全類最優先（自傷、醫療、法律…）。這些不能因為句子裡剛好有
//       「今天」兩個字就被曆法意圖搶走——例如「我媽住院了，今天適合開刀嗎？」
//    2. exact 完全比對（處理「好」「嗯嗯」「？」這種短輸入）。
//    3. 其餘用「最長關鍵字優先」，避免「今天」這種泛用詞把所有問題吸走
//       （舊版罐頭腳本就是這樣，12 題曆法基礎裡 10 題掉進同一段過期文字）。
export function localAnswer(text, day) {
  const raw = String(text || '').trim()
  if (!raw) return null
  const q = toTrad(raw).toLowerCase()

  // ⚠️ 這個 catch 是為了「曆訊缺某個欄位時安靜讓給 GPT，不要讓整頁壞掉」，
  //    但它也會把 handler 裡的打字錯誤（例如忘了 import）一起吞掉——
  //    症狀是該意圖安靜失效、問題被丟給 GPT，完全沒有任何跡象。
  //    （實測就踩過一次：termGuideOf 忘了 import，整條節氣養生意圖靜靜失聯。）
  //    所以保留容錯，但一定要留下痕跡。
  const run = (it) => {
    try {
      const r = it.fn(day)
      return r ? { ...r, intent: it.id } : null
    } catch (e) {
      console.warn(`[aiKnowledge] 意圖 "${it.id}" 執行失敗，已讓給 GPT：`, e?.message)
      return null
    }
  }

  // 1) 安全類優先
  for (const it of INTENTS) {
    if (!it.safety) continue
    if ((it.keys || []).some(k => q.includes(toTrad(k).toLowerCase()))) return run(it)
  }
  // 2) 短輸入完全比對
  for (const it of INTENTS) {
    if ((it.exact || []).some(e => q === toTrad(e).toLowerCase())) return run(it)
  }
  // 3) 最長關鍵字優先（notKeys 命中就整條略過——見 interview 的註解）
  let best = null
  for (const it of INTENTS) {
    if ((it.notKeys || []).some(nk => q.includes(toTrad(nk).toLowerCase()))) continue
    for (const k of it.keys || []) {
      const kk = toTrad(k).toLowerCase()
      if (q.includes(kk) && (!best || kk.length > best.len)) best = { it, len: kk.length }
    }
  }
  return best ? run(best.it) : null
}

export const LOCAL_INTENT_COUNT = INTENTS.length
